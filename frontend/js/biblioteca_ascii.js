        /**
         * Dibuja un arte ASCII directamente sobre un contexto Canvas 2D
         */
        renderizarArte: function(ctx, lineasArte, posX, posY, opciones = {}) {
            if (!ctx || !Array.isArray(lineasArte) || lineasArte.length === 0) return;

            const fuente = opciones.fuente || '12px "Fira Code", monospace';
            const color = opciones.color || '#a6e3a1';
            const alineacion = opciones.alineacion || 'center';
            const interlineado = opciones.interlineado || 13;
            const resplandorColor = opciones.resplandorColor || null;
            const resplandorBlur = opciones.resplandorBlur || 0;

            ctx.save();
            ctx.font = fuente;
            ctx.fillStyle = color;
            ctx.textAlign = alineacion;

            if (resplandorColor && resplandorBlur > 0) {
                ctx.shadowColor = resplandorColor;
                ctx.shadowBlur = resplandorBlur;
            }

            const totalLineas = lineasArte.length;
            const inicioY = posY - (totalLineas * interlineado) / 2;

            for (let i = 0; i < totalLineas; i++) {
                ctx.fillText(lineasArte[i], posX, inicioY + i * interlineado);
            }

            ctx.restore();
        },

        /**
         * Obtiene un arte por categoría y clave
         */
        obtener: function(categoria, clave) {
            if (this[categoria] && this[categoria][clave]) {
                return this[categoria][clave];
            }
            return null;
        },

        /**
         * Lista todas las categorías disponibles
         */
        listarCategorias: function() {
            return Object.keys(this).filter(k => typeof this[k] === 'object' && k !== 'RAMPAS');
        },

        /**
         * Lista todas las claves dentro de una categoría
         */
        listar: function(categoria) {
            if (this[categoria]) {
                return Object.keys(this[categoria]);
            }
            return [];
        },

        /**
         * Obtiene un arte aleatorio de una categoría dada o de toda la biblioteca
         */
        obtenerAleatorio: function(categoria = null) {
            if (!categoria) {
                const cats = this.listarCategorias();
                if (cats.length === 0) return null;
                categoria = cats[Math.floor(Math.random() * cats.length)];
            }
            const claves = this.listar(categoria);
            if (claves.length === 0) return null;
            const elegida = claves[Math.floor(Math.random() * claves.length)];
            return { categoria, id: elegida, arte: this[categoria][elegida] };
        }
